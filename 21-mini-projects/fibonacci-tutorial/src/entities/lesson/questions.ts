export function getTheoryQuestions(id: string): { questions: LessonQuestion[]; correctAnswers: number[] } {
  const seeds = questionsByUnit[id];
  if (!seeds) throw new Error(`Missing theory questions: ${id}`);
  return {
    questions: seeds.map(([prompt, options], index) => ({ id: `q${index + 1}`, prompt, options: [...options] })),
    correctAnswers: seeds.map(([, , correct]) => correct),
  };
}
