export function validatePremiumCast() {
  const errors: string[] = []
  const signatures = new Set<string>()
  const ids = new Set<string>()
  for (const [room, cast] of Object.entries(PREMIUM_ROOM_CAST))
    for (const id of cast) {
      const p = PREMIUM_CAST[id]
      if (!p || p.spaceId !== room || p.id !== id) errors.push(`Invalid room cast ${room}:${id}`)
      if (ids.has(id)) errors.push(`Reused cast ${id}`)
      ids.add(id)
      if (p) {
        if (signatures.has(p.signature)) errors.push(`Reused appearance ${id}`)
        signatures.add(p.signature)
      }
    }
  if (ids.size !== Object.keys(PREMIUM_CAST).length) errors.push('Orphan cast')
  return errors
}
