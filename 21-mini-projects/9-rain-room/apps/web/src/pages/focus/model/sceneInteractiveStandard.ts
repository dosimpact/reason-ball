function discovery(
  roomId: string,
  key: string,
  labels: Labels,
  x: number,
  y: number,
  scale: number,
  note: string,
  base: string,
  subject: string,
  type: SceneObjectReaction,
  description: string,
  color = '#b6a47c',
  kind: SceneInteractiveObject['surface']['kind'] = 'table',
  pivot = { x: 48, y: 78 },
  durationMs = 1700,
): SceneInteractiveObject {
  return {
    id: `${roomId}:${key}`,
    roomId,
    label: { ko: labels[0], en: labels[1], zh: labels[2] },
    position: { x, y },
    scale,
    surface: { kind, note },
    art: { base: kind === 'table' ? shadow + base : base, subject, pivot },
    reaction: { type, durationMs, color, description },
  }
}

