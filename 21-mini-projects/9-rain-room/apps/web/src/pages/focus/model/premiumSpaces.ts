export function getPremiumSpace(id: string): PremiumSpace | undefined {
  return PREMIUM_SPACES.find((space) => space.id === id)
}

export function validatePremiumSpaces(): string[] {
  const errors: string[] = []
  if (PREMIUM_SPACES.length !== 30) errors.push('premium catalog must contain 30 spaces')
  for (const group of PREMIUM_GROUPS)
    if (PREMIUM_SPACES.filter((space) => space.group === group.id).length !== 5)
      errors.push(`premium group must contain five spaces: ${group.id}`)
  for (const space of PREMIUM_SPACES)
    if (
      !space.id.startsWith('premium-') ||
      !space.available ||
      !['epic', 'legendary'].includes(space.rarity) ||
      !space.name ||
      !space.description ||
      !space.signature ||
      !space.motion ||
      !Number.isInteger(space.coffeeMilestone) ||
      space.coffeeMilestone < 1 ||
      space.scene < 38 ||
      space.scene > 67
    )
      errors.push(`invalid premium space: ${space.id}`)
  return errors
}
